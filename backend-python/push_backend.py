"""Opt-in Web Push using the existing PostgreSQL notification transaction."""
import asyncio
import base64
import hashlib
import json
import logging
import os
from urllib.parse import urlsplit

from fastapi import Header, HTTPException
from pydantic import BaseModel, Field
from starlette.concurrency import run_in_threadpool
from pywebpush import webpush, WebPushException
import requests

log = logging.getLogger('noveam.push')


class PushSession(requests.Session):
    def post(self, url, **kwargs):
        if not endpoint_allowed(url):
            raise ValueError('Unsupported push endpoint')
        kwargs['allow_redirects'] = False
        return super().post(url, **kwargs)


def config():
    return (os.getenv('VAPID_PUBLIC_KEY', '').strip(),
            os.getenv('VAPID_PRIVATE_KEY', '').strip(),
            os.getenv('VAPID_SUBJECT', '').strip())


def configured():
    public, private, subject = config()
    return bool(public and private and subject.startswith(('mailto:', 'https://')))


def endpoint_allowed(endpoint):
    try:
        url = urlsplit(endpoint)
        host = (url.hostname or '').lower()
        allowed = host in {'fcm.googleapis.com', 'web.push.apple.com', 'updates.push.services.mozilla.com'}
        allowed |= host.endswith('.push.services.mozilla.com') or host.endswith('.notify.windows.com')
        return bool(allowed and url.scheme == 'https' and url.port in (None, 443)
                    and not url.username and not url.password and not url.fragment and url.path)
    except ValueError:
        return False


def decode_key(value, size):
    try:
        import re
        if not re.fullmatch(r'[A-Za-z0-9_-]+={0,2}', value):
            raise ValueError()
        decoded = base64.urlsafe_b64decode(value + '=' * (-len(value) % 4))
        if len(decoded) != size:
            raise ValueError()
        return decoded
    except Exception:
        raise HTTPException(422, 'Invalid subscription keys') from None


class Subscription(BaseModel):
    endpoint: str = Field(min_length=15, max_length=2048)
    keys: dict[str, str]


class Device(BaseModel):
    subscription_id: str = Field(pattern=r'^[0-9a-f]{64}$')


def initialize_push_database(db):
    with db() as conn:
        conn.execute('SELECT pg_advisory_xact_lock(726683217)')
        conn.execute('''CREATE TABLE IF NOT EXISTS push_subscriptions (
            id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            endpoint TEXT NOT NULL, p256dh TEXT NOT NULL, auth TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            last_test_at TIMESTAMPTZ)''')
        conn.execute('CREATE INDEX IF NOT EXISTS push_subscriptions_user ON push_subscriptions(user_id)')
        conn.execute('''CREATE TABLE IF NOT EXISTS push_deliveries (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            subscription_id TEXT NOT NULL REFERENCES push_subscriptions(id) ON DELETE CASCADE,
            notification_id INTEGER REFERENCES notifications(id) ON DELETE CASCADE,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(), available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            attempts INTEGER NOT NULL DEFAULT 0, finished_at TIMESTAMPTZ,
            UNIQUE(subscription_id,notification_id))''')
        conn.execute('CREATE INDEX IF NOT EXISTS push_deliveries_pending ON push_deliveries(available_at,id) WHERE finished_at IS NULL')


def enqueue_push(conn, notification_id, user_id):
    # The original notification and queue rows commit or roll back together.
    conn.execute('''INSERT INTO push_deliveries(subscription_id,notification_id,user_id)
        SELECT id,%s,user_id FROM push_subscriptions WHERE user_id=%s
        ON CONFLICT(subscription_id,notification_id) DO NOTHING''', (notification_id, user_id))


def still_allowed(conn, row):
    setting = conn.execute('SELECT notifications FROM user_settings WHERE user_id=%s', (row['user_id'],)).fetchone()
    if setting and not bool(setting['notifications']):
        return False
    if row['type'] in ('NEW_MESSAGE', 'INCOMING_CALL'):
        preferences = conn.execute('''SELECT message_notifications,incoming_call_notifications
            FROM communication_settings WHERE user_id=%s''', (row['user_id'],)).fetchone()
        key = 'message_notifications' if row['type'] == 'NEW_MESSAGE' else 'incoming_call_notifications'
        if preferences and not bool(preferences[key]):
            return False
        muted = conn.execute('''SELECT 1 FROM conversation_controls WHERE user_id=%s
            AND peer_user_id=%s AND (muted=1 OR blocked=1)''', (row['user_id'], row['actor_user_id'])).fetchone()
        if muted:
            return False
    return True


def notification_payload(row):
    kind = row.get('type')
    body = {'NEW_MESSAGE': 'You have a new message.', 'INCOMING_CALL': 'Someone called you on NOVEAM.'}.get(kind, 'You have a new notification.')
    if row.get('notification_id') is None:
        body = 'Push notifications are working on this device.'
    return {'title': 'NOVEAM', 'body': body, 'url': '/notifications.html', 'user_id': str(row['user_id']),
            'tag': 'noveam-' + str(row.get('notification_id') or ('test-' + str(row['id'])))}


def deliver_one(db):
    if not configured():
        return False
    # A row lock prevents two server processes sending the same job concurrently.
    # Keep bounded network work off the event loop and outside application requests.
    with db() as conn:
        row = conn.execute('''SELECT d.*,s.endpoint,s.p256dh,s.auth,n.type,n.actor_user_id,n.read_at,
                EXTRACT(EPOCH FROM (now()-d.created_at)) AS age
            FROM push_deliveries d JOIN push_subscriptions s ON s.id=d.subscription_id AND s.user_id=d.user_id
            LEFT JOIN notifications n ON n.id=d.notification_id
            WHERE d.finished_at IS NULL AND d.available_at<=now()
            ORDER BY d.available_at,d.id FOR UPDATE OF d SKIP LOCKED LIMIT 1''').fetchone()
        if not row:
            return False
        expire = 90 if row['type'] == 'INCOMING_CALL' else 3600
        if row['age'] > expire or row['read_at'] or not still_allowed(conn, row) or not endpoint_allowed(row['endpoint']):
            conn.execute('UPDATE push_deliveries SET finished_at=now() WHERE id=%s', (row['id'],))
            return True
        public, private, subject = config()
        try:
            with PushSession() as session:
                webpush(subscription_info={'endpoint': row['endpoint'], 'keys': {'p256dh': row['p256dh'], 'auth': row['auth']}},
                        data=json.dumps(notification_payload(row)), vapid_private_key=private,
                        vapid_claims={'sub': subject}, ttl=30 if row['type'] == 'INCOMING_CALL' else 3600,
                        timeout=8, requests_session=session)
            conn.execute('UPDATE push_deliveries SET finished_at=now() WHERE id=%s', (row['id'],))
        except WebPushException as error:
            response = getattr(error, 'response', None)
            code = getattr(response, 'status_code', None)
            if code in (404, 410):
                conn.execute('DELETE FROM push_subscriptions WHERE id=%s', (row['subscription_id'],))
            else:
                retry_delivery(conn, row)
                log.warning('push_delivery_failed status=%s', code)
        except Exception:
            retry_delivery(conn, row)
            log.warning('push_delivery_failed')
        return True


def retry_delivery(conn, row):
    attempt = row['attempts'] + 1
    conn.execute('''UPDATE push_deliveries SET attempts=%s,
        available_at=now()+(%s * interval '1 second'),
        finished_at=CASE WHEN %s>=6 THEN now() ELSE NULL END WHERE id=%s''',
        (attempt, min(900, 15 * 2 ** attempt), attempt, row['id']))


async def push_worker(db):
    cleanup_ticks = 0
    while True:
        try:
            worked = await run_in_threadpool(deliver_one, db)
            cleanup_ticks += 1
            if cleanup_ticks >= 360:
                await run_in_threadpool(cleanup_deliveries, db)
                cleanup_ticks = 0
        except asyncio.CancelledError:
            raise
        except Exception:
            log.warning('push_worker_retry')
            worked = False
        await asyncio.sleep(0.1 if worked else 10)


def cleanup_deliveries(db):
    with db() as conn:
        conn.execute('''DELETE FROM push_deliveries WHERE id IN
            (SELECT id FROM push_deliveries WHERE finished_at<now()-interval '7 days' LIMIT 1000)''')


def install_push_routes(app, db, current_user):
    @app.get('/api/push/config')
    def push_config():
        return {'enabled': configured(), 'public_key': config()[0] if configured() else ''}

    @app.post('/api/push/subscriptions')
    def subscribe(payload: Subscription, authorization: str | None = Header(default=None)):
        user, _ = current_user(authorization)
        if not configured():
            raise HTTPException(503, 'Push notifications are not configured yet')
        if not endpoint_allowed(payload.endpoint):
            raise HTTPException(422, 'Unsupported push-service endpoint')
        p256dh, auth = payload.keys.get('p256dh', ''), payload.keys.get('auth', '')
        if set(payload.keys) != {'p256dh', 'auth'} or len(p256dh) > 90 or len(auth) > 26:
            raise HTTPException(422, 'Invalid subscription keys')
        decoded = decode_key(p256dh, 65)
        if decoded[0] != 4:
            raise HTTPException(422, 'Invalid subscription key')
        try:
            from cryptography.hazmat.primitives.asymmetric import ec
            ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), decoded)
        except ValueError:
            raise HTTPException(422, 'Invalid subscription key') from None
        decode_key(auth, 16)
        sid = hashlib.sha256(payload.endpoint.encode()).hexdigest()
        with db() as conn:
            conn.execute('SELECT pg_advisory_xact_lock(%s)', (int(user['id']),))
            existing = conn.execute('SELECT user_id FROM push_subscriptions WHERE id=%s FOR UPDATE', (sid,)).fetchone()
            count = conn.execute('SELECT count(*) AS n FROM push_subscriptions WHERE user_id=%s', (user['id'],)).fetchone()['n']
            if count >= 10 and (not existing or existing['user_id'] != user['id']):
                raise HTTPException(409, 'Device limit reached. Disable notifications on an older device first.')
            # When the same browser changes accounts, discard the previous owner's pending jobs.
            if existing and existing['user_id'] != user['id']:
                conn.execute('DELETE FROM push_deliveries WHERE subscription_id=%s', (sid,))
            conn.execute('''INSERT INTO push_subscriptions(id,user_id,endpoint,p256dh,auth) VALUES(%s,%s,%s,%s,%s)
                ON CONFLICT(id) DO UPDATE SET user_id=excluded.user_id,p256dh=excluded.p256dh,
                auth=excluded.auth,updated_at=now()''', (sid,user['id'],payload.endpoint,p256dh,auth))
        return {'subscription_id': sid}

    @app.post('/api/push/unsubscribe')
    def unsubscribe(payload: Device, authorization: str | None = Header(default=None)):
        user, _ = current_user(authorization)
        with db() as conn:
            conn.execute('DELETE FROM push_subscriptions WHERE id=%s AND user_id=%s', (payload.subscription_id,user['id']))
        return {'ok': True}

    @app.post('/api/push/test')
    def test_push(payload: Device, authorization: str | None = Header(default=None)):
        user, _ = current_user(authorization)
        if not configured():
            raise HTTPException(503, 'Push notifications are not configured yet')
        with db() as conn:
            row = conn.execute('''UPDATE push_subscriptions SET last_test_at=now() WHERE id=%s AND user_id=%s
                AND (last_test_at IS NULL OR last_test_at<now()-interval '1 minute') RETURNING id''',
                (payload.subscription_id,user['id'])).fetchone()
            if not row:
                raise HTTPException(409, 'Enable this device first, or wait one minute before another test')
            conn.execute('INSERT INTO push_deliveries(subscription_id,user_id) VALUES(%s,%s)', (row['id'],user['id']))
        return {'queued': True}
